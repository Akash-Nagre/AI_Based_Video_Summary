
import numpy as np


def calculate_base_scores(
    text_scores: np.ndarray,
    visual_scores: np.ndarray,
    temporal_scores: np.ndarray,
    text_weight: float = 0.70,
    visual_weight: float = 0.15,
    temporal_weight: float = 0.15,
) -> np.ndarray:
    """Combine comparable text, visual, and temporal scores."""

    text_scores = np.asarray(text_scores, dtype=float)
    visual_scores = np.asarray(visual_scores, dtype=float)
    temporal_scores = np.asarray(temporal_scores, dtype=float)

    if not (
        len(text_scores)
        == len(visual_scores)
        == len(temporal_scores)
    ):
        raise ValueError("Score arrays must have equal lengths.")

    weights = (text_weight, visual_weight, temporal_weight)

    if not all(np.isfinite(weight) and weight >= 0 for weight in weights):
        raise ValueError("Weights must be finite and non-negative.")

    if not np.isclose(sum(weights), 1.0):
        raise ValueError("Weights must sum to 1.")

    if not all(
        np.all(np.isfinite(scores))
        for scores in (text_scores, visual_scores, temporal_scores)
    ):
        raise ValueError("Scores must contain finite values.")

    return (
        text_weight * text_scores
        + visual_weight * visual_scores
        + temporal_weight * temporal_scores
    )


def _interval_gap(a: dict, b: dict) -> float:
    """Return the time gap between two segments, or zero if they overlap."""

    return max(
        0.0,
        max(a["start"], b["start"]) - min(a["end"], b["end"]),
    )


def select_highlights(
    segments: list,
    base_scores: np.ndarray,
    embeddings: np.ndarray,
    number_of_highlights: int = 3,
    diversity_weight: float = 0.35,
    minimum_gap: float = 15.0,
    max_duration_seconds: float | None = None,
    topic_ids: list | None = None,
    topic_importance: dict | None = None,
    minimum_topic_seconds: dict | None = None,
) -> list:
    """
    Select important, diverse, temporally separated segments.

    The requested minimum gap is relaxed if necessary to find
    the requested number of highlights.
    """

    if not segments:
        return []

    if (
        not isinstance(number_of_highlights, int)
        or isinstance(number_of_highlights, bool)
    ):
        raise ValueError("number_of_highlights must be an integer.")

    if number_of_highlights <= 0:
        return []

    base_scores = np.asarray(base_scores, dtype=float)
    embeddings = np.asarray(embeddings, dtype=float)

    if base_scores.ndim != 1 or len(base_scores) != len(segments):
        raise ValueError("One score is required per segment.")

    if embeddings.ndim != 2 or len(embeddings) != len(segments):
        raise ValueError("One embedding is required per segment.")

    if embeddings.shape[1] == 0:
        raise ValueError("Embeddings must have at least one dimension.")

    if not np.all(np.isfinite(base_scores)):
        raise ValueError("Scores must be finite.")

    if not np.all(np.isfinite(embeddings)):
        raise ValueError("Embeddings must be finite.")

    if not np.isfinite(diversity_weight) or not 0 <= diversity_weight <= 1:
        raise ValueError("diversity_weight must be between 0 and 1.")

    if not np.isfinite(minimum_gap) or minimum_gap < 0:
        raise ValueError("minimum_gap must be finite and non-negative.")

    for segment in segments:
        try:
            start = float(segment["start"])
            end = float(segment["end"])
        except (KeyError, TypeError, ValueError) as exc:
            raise ValueError("Each segment needs valid start and end times.") from exc

        if not np.isfinite(start) or not np.isfinite(end) or end <= start:
            raise ValueError("Every segment must have finite times and end > start.")

    target = min(number_of_highlights, len(segments))

    # Embeddings generated by generate_embeddings() are normalized.
    similarity = np.clip(embeddings @ embeddings.T, 0.0, 1.0)

    if max_duration_seconds is not None and (
        not np.isfinite(max_duration_seconds) or max_duration_seconds <= 0
    ):
        raise ValueError("max_duration_seconds must be positive when provided.")
    if topic_ids is not None and len(topic_ids) != len(segments):
        raise ValueError("One topic id is required per segment.")

    # Greedy marginal utility balances salience, novelty and topic coverage
    # while honoring a duration budget. The budget mode adapts clip count.
    durations = np.asarray([float(s["end"]) - float(s["start"]) for s in segments])
    selected = []
    remaining = list(range(len(segments)))
    covered_topics = set()
    topic_seconds = {}
    selected_time_bins = set()
    topic_importance = topic_importance or {}
    minimum_topic_seconds = minimum_topic_seconds or {}
    video_start = min(float(s["start"]) for s in segments)
    video_end = max(float(s["end"]) for s in segments)
    selected_duration = 0.0

    # Treat the requested gap as a preference, not a staged hard constraint:
    # staging can consume the whole budget with one topic before considering
    # nearby clips that would cover missing topics. Overlap is always blocked.
    gap_levels = [0.0]

    for gap in gap_levels:
        while len(selected) < target and remaining:
            best_index = None
            best_score = -float("inf")

            for index in remaining:
                separated = all(
                    (float(segments[index]["end"]) <= float(segments[chosen]["start"]) or
                     float(segments[index]["start"]) >= float(segments[chosen]["end"]))
                    and _interval_gap(segments[index], segments[chosen]) >= gap
                    for chosen in selected
                )

                if not separated:
                    continue

                redundancy = max((similarity[index, chosen] for chosen in selected), default=0.0)
                topic_bonus = 0.0
                if topic_ids is not None:
                    topic = topic_ids[index]
                    importance = float(topic_importance.get(topic, 1.0))
                    target_seconds = float(minimum_topic_seconds.get(topic, durations[index]))
                    before = min(1.0, topic_seconds.get(topic, 0.0) / max(target_seconds, 1e-6))
                    after = min(1.0, (topic_seconds.get(topic, 0.0) + durations[index]) / max(target_seconds, 1e-6))
                    # Reserve meaningful marginal value for a first useful
                    # passage from an uncovered topic. Importance still
                    # scales that reward, while repeated coverage saturates.
                    topic_bonus = (0.30 + 0.70 * importance) * max(0.0, after - before)
                position = ((float(segments[index]["start"]) + float(segments[index]["end"])) / 2 - video_start) / max(video_end-video_start, 1e-6)
                time_bin = min(2, int(position * 3))
                timeline_bonus = 0.08 if time_bin not in selected_time_bins else 0.0

                mmr_score = (
                    (1.0 - diversity_weight) * base_scores[index]
                    - diversity_weight * redundancy + topic_bonus + timeline_bonus
                )
                if selected and minimum_gap > 0:
                    nearest_gap = min(_interval_gap(segments[index], segments[chosen]) for chosen in selected)
                    gap_shortfall = max(0.0, minimum_gap - nearest_gap) / minimum_gap
                    mmr_score -= 0.08 * gap_shortfall
                if max_duration_seconds is not None and selected_duration + durations[index] > max_duration_seconds:
                    continue

                if mmr_score > best_score:
                    best_score = mmr_score
                    best_index = index

            if best_index is None:
                break

            selected.append(best_index)
            selected_duration += float(durations[best_index])
            remaining.remove(best_index)
            if topic_ids is not None:
                covered_topics.add(topic_ids[best_index])
                topic_seconds[topic_ids[best_index]] = topic_seconds.get(topic_ids[best_index], 0.0) + durations[best_index]
            position = ((float(segments[best_index]["start"]) + float(segments[best_index]["end"])) / 2 - video_start) / max(video_end-video_start, 1e-6)
            selected_time_bins.add(min(2, int(position * 3)))

        # With a duration budget, do not relax temporal separation by adding
        # clips that exceed the budget. Continue with smaller gaps if useful.

        if len(selected) >= target:
            break

    # If no single candidate fits (for example a very short source and a clip
    # boundary longer than the target), retain the best complete candidate.
    if not selected and remaining:
        selected = [max(remaining, key=lambda i: float(base_scores[i]))]

    # Return highlights in video order.
    selected.sort(key=lambda i: float(segments[i]["start"]))

    results = []

    for index in selected:
        item = segments[index].copy()
        item["base_score"] = float(base_scores[index])
        if topic_ids is not None:
            item["topic_id"] = topic_ids[index]
        results.append(item)

    return results
